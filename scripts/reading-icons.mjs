// Writes workers/reading/icons.js: the Lucide icons the private reading app
// uses, as inline SVG strings, copied verbatim from @lucide/astro (ISC). The
// app is served by the Worker, which cannot use Astro components.
//   node scripts/reading-icons.mjs
import fs from "node:fs";

const ICONS = {
  today: "sun", review: "layers", words: "list", sentences: "quote", progress: "chart-column", admin: "settings",
  check: "check", circle: "circle", sync: "refresh-cw", download: "download", key: "key-round", search: "search",
  offline: "wifi-off", close: "x", plus: "plus", pencil: "pencil", trash: "trash-2", volume: "volume-2",
  logout: "log-out", language: "languages", chevron: "chevron-down",
};
const dir = new URL("../node_modules/@lucide/astro/", import.meta.url);
const version = JSON.parse(fs.readFileSync(new URL("package.json", dir), "utf8")).version;
const lines = [
  `// Lucide icons (ISC licence, lucide.dev) from @lucide/astro ${version}. Generated by scripts/reading-icons.mjs; do not edit.`,
  "const svg = (body) =>",
  '  `<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;',
  "",
];
for (const [name, file] of Object.entries(ICONS)) {
  const src = fs.readFileSync(new URL(`src/icons/${file}.ts`, dir), "utf8");
  const node = JSON.parse(src.match(/createLucideIcon\('[^']+', (\[.*\])\)/)[1]);
  const body = node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("");
  lines.push(`export const ${name} = svg(${JSON.stringify(body)});`);
}
fs.writeFileSync(new URL("../workers/reading/icons.js", import.meta.url), lines.join("\n") + "\n");
console.log(`${Object.keys(ICONS).length} icons -> workers/reading/icons.js`);
